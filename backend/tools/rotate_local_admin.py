"""One-time upgrade of an existing LOCAL Compose database to the new admin secret.

Uses the existing container's Unix socket. Stop api/collector first, then run this
script and `docker compose up -d --build`. Never removes a volume or prints secrets.
"""
import argparse
from pathlib import Path
import re
import subprocess


def rotate(directory: Path) -> None:
    password = (directory / "postgres_admin_password").read_text().strip()
    if not re.fullmatch(r"[0-9a-f]{64}", password):
        raise ValueError("Expected an admin secret generated by init_secrets.py")
    # COPY data stays out of SQL statement text and command-line arguments.
    statement = (
        "BEGIN;\nCREATE TEMP TABLE kickpick_new_password (value text) ON COMMIT DROP;\n"
        "COPY kickpick_new_password FROM STDIN;\n" + password + "\n\\.\n"
        "DO $$ BEGIN EXECUTE format('ALTER ROLE kickpick PASSWORD %L', "
        "(SELECT value FROM kickpick_new_password)); END $$;\nCOMMIT;\n"
    )
    result = subprocess.run(
        ["docker", "compose", "exec", "-T", "db", "psql", "-X", "-v", "ON_ERROR_STOP=1",
         "-U", "kickpick", "-d", "kickpick"],
        input=statement, text=True, capture_output=True, cwd=Path(__file__).resolve().parents[2],
    )
    if result.returncode:
        raise RuntimeError("Admin rotation failed; diagnostics withheld to avoid exposing the secret. "
                           "Check that the local db container is running and Unix-socket access is allowed.")
    print("Local database admin password updated. Start the hardened Compose stack next.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, default=Path(__file__).resolve().parents[2] / ".secrets")
    rotate(parser.parse_args().directory)
