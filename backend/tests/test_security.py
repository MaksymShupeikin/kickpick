import secrets

import psycopg
from psycopg import sql
import pytest
from sqlalchemy.engine import make_url

from kickpick import config, provision_db
from tools.init_secrets import NAMES, initialize


def test_database_url_uses_secret_file_and_quotes_password(monkeypatch, tmp_path):
    path = tmp_path / "password"
    path.write_text("a password:@/?#'\n")
    monkeypatch.delenv("DATABASE_URL", raising=False)
    monkeypatch.setenv("DATABASE_USER", "readonly")
    monkeypatch.setenv("DATABASE_PASSWORD_FILE", str(path))
    url = config.database_url()
    assert url.username == "readonly" and url.password == "a password:@/?#'"
    assert make_url(url.render_as_string(hide_password=False)).password == url.password
    monkeypatch.delenv("DATABASE_PASSWORD_FILE")
    with pytest.raises(RuntimeError, match="DATABASE_PASSWORD_FILE"):
        config.database_url()


def test_generated_secrets_are_private_unique_and_preserved(tmp_path, capsys):
    directory = tmp_path / "secrets"
    initialize(directory)
    values = {name: (directory / name).read_text() for name in NAMES}
    initialize(directory)
    assert len(set(values.values())) == len(NAMES)
    assert all((directory / name).read_text() == value for name, value in values.items())
    assert directory.stat().st_mode & 0o777 == 0o700
    output = capsys.readouterr().out
    assert all(value.strip() not in output for value in values.values())


def test_database_roles_enforce_permissions_and_future_table_grants(engine, monkeypatch):
    # Temporary roles and the *_test database only; never change the running app's roles.
    assert engine.url.database.endswith("_test")
    prefix = "kp_test_" + secrets.token_hex(5)
    roles = {key: f"{prefix}_{key}" for key in provision_db.ROLES}
    passwords = {key: secrets.token_hex(24) for key in roles}
    monkeypatch.setattr(provision_db, "ROLES", roles)
    options = engine.url.translate_connect_args(database="dbname", username="user")

    def connect(key):
        return psycopg.connect(**(options | {"user": roles[key], "password": passwords[key]}), autocommit=True)

    with psycopg.connect(**options, autocommit=True) as admin:
        try:
            for _ in range(2):  # existing tables + a repeated provisioning run
                with admin.transaction():
                    provision_db.provision(admin, passwords)
            with connect("migrator") as migrator:
                migrator.execute("CREATE TABLE public.security_permissions_probe "
                                 "(id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text)")
            with connect("api") as api:
                assert api.execute("SHOW default_transaction_read_only").fetchone()[0] == "on"
                assert api.execute("SELECT count(*) FROM public.security_permissions_probe").fetchone()[0] == 0
                # Verify ACLs still deny writes even when the extra read-only default is disabled.
                api.execute("SET default_transaction_read_only = off")
                for statement in (
                    "INSERT INTO public.security_permissions_probe(value) VALUES ('forbidden')",
                    "UPDATE public.security_permissions_probe SET value='forbidden'",
                    "DELETE FROM public.security_permissions_probe",
                    "DROP TABLE public.security_permissions_probe",
                    "CREATE TABLE public.forbidden_table(id integer)",
                    "SELECT rolpassword FROM pg_authid",
                ):
                    with pytest.raises(psycopg.errors.InsufficientPrivilege):
                        api.execute(statement)
                with pytest.raises(psycopg.errors.InsufficientPrivilege):
                    api.execute(sql.SQL("SET ROLE {}").format(sql.Identifier(roles["migrator"])))
                assert api.execute("SELECT rolsuper,rolcreatedb,rolcreaterole,rolbypassrls "
                                   "FROM pg_roles WHERE rolname=current_user").fetchone() == (False,) * 4
            with connect("collector") as collector:
                row_id = collector.execute("INSERT INTO public.security_permissions_probe(value) "
                                           "VALUES ('collected') RETURNING id").fetchone()[0]
                collector.execute("UPDATE public.security_permissions_probe SET value='updated' WHERE id=%s", (row_id,))
                assert collector.execute("SELECT value FROM public.security_permissions_probe").fetchone()[0] == "updated"
                collector.execute("DELETE FROM public.security_permissions_probe WHERE id=%s", (row_id,))
                for statement in ("TRUNCATE public.security_permissions_probe",
                                  "ALTER TABLE public.security_permissions_probe ADD COLUMN forbidden text",
                                  "INSERT INTO prediction_models(version,bundle_sha256,metadata) VALUES ('forbidden','x','{}')"):
                    with pytest.raises(psycopg.errors.InsufficientPrivilege):
                        collector.execute(statement)
            with connect("predictor") as predictor:
                assert predictor.execute("SELECT count(*) FROM matches").fetchone()[0] >= 0
                predictor.execute("INSERT INTO prediction_models(version,bundle_sha256,metadata) VALUES ('allowed','x','{}')")
                for statement in ("UPDATE matches SET status='LIVE'", "DELETE FROM match_predictions",
                                  "INSERT INTO public.security_permissions_probe(value) VALUES ('forbidden')",
                                  "CREATE TABLE public.predictor_forbidden(id integer)"):
                    with pytest.raises(psycopg.errors.InsufficientPrivilege):
                        predictor.execute(statement)
        finally:
            admin.execute("DROP TABLE IF EXISTS public.security_permissions_probe")
            # Keep fixture tables for later tests, remove only temporary roles and grants.
            for name in roles.values():
                if admin.execute("SELECT 1 FROM pg_roles WHERE rolname=%s", (name,)).fetchone():
                    admin.execute(sql.SQL("REASSIGN OWNED BY {} TO {}")
                                  .format(sql.Identifier(name), sql.Identifier(options["user"])))
                    admin.execute(sql.SQL("DROP OWNED BY {}").format(sql.Identifier(name)))
                    admin.execute(sql.SQL("DROP ROLE {}").format(sql.Identifier(name)))
